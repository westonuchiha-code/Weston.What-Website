def glyph(ch):
    rows = GLYPHS.get(ch.upper(), GLYPHS["?"]).split("|")
    return rows


def text_width(text, spacing=1):
    w = 0
    for ch in text:
        w += len(glyph(ch)[0]) + spacing
    return max(0, w - spacing)


def draw_text(img, x, y, text, color, scale=1, spacing=1, shadow=None):
    """Draw text onto a PIL RGB/RGBA image. color may be a tuple or a function(col,row)->tuple."""
    px = img.load()
    cx = x
    for ch in text:
        rows = glyph(ch)
        for r, line in enumerate(rows):
            for c, bit in enumerate(line):
                if bit != "#":
                    continue
                col = color(cx + c * scale, y + r * scale) if callable(color) else color
                for dy in range(scale):
                    for dx in range(scale):
                        X, Y = cx + c * scale + dx, y + r * scale + dy
                        if shadow is not None:
                            sx, sy = X + scale, Y + scale
                            if 0 <= sx < img.width and 0 <= sy < img.height:
                                px[sx, sy] = shadow
                        if 0 <= X < img.width and 0 <= Y < img.height:
                            px[X, Y] = col
        cx += (len(rows[0]) + spacing) * scale
    return cx


def draw_text_centered(img, cy, text, color, scale=1, spacing=1, shadow=None, cx=None):
    w = text_width(text, spacing) * scale
    x = ((img.width if cx is None else cx * 2) - w) // 2
    return draw_text(img, x, cy, text, color, scale, spacing, shadow)
